#!/usr/bin/env node
/**
 * Cross-language check for the locus recipe serialisation (place#172, place#325 Stage 1).
 *
 * The locus PID is sha256 over the canonical recipe bytes, and the unminted soft-cluster URL
 * is a token of those same bytes. The browser builds the token from a tuned cluster; the
 * server rebuilds and hashes it. If the two canonicalisers disagree on a single byte, the
 * same cluster gets two names. So the contract is EXACT EQUALITY of canonical text, token and
 * PID between whg/webpack/js/locus_recipe.js (the shipped browser module, not a copy) and
 * places/locus_recipe.py, on every vector in scripts/fixtures/locus_recipe_vectors.json.
 *
 * The vectors are generated by the Python module (the reference). Each one reaches a rule
 * that could plausibly diverge: key order, code-point vs UTF-16 sort, half-up ties on the
 * shortest decimal repr, NFC, whitespace class, case folding, list de-duplication,
 * GeometryCollection unwrapping, and the rejection paths (the error PATH must match too).
 *
 * Run with `npm run test:locus-recipe`. Exits non-zero listing every failing case.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const mod = await import(path.join(ROOT, 'whg', 'webpack', 'js', 'locus_recipe.js'));
const {
	RECIPE_VERSION, RecipeError, parseRecipe, canonicalJson, recipePid, encodeRecipeToken,
	decodeRecipeToken, retrievalFromSearchBody, normalisePid, isLegacyLocusId, PID_RE,
} = mod;

// LOCUS_RECIPE_VECTORS points at another fixture; the Django test uses it to prove this
// checker fails on a tampered vector (a parity check that cannot fail proves nothing).
const VECTORS = process.env.LOCUS_RECIPE_VECTORS || path.join(HERE, 'fixtures', 'locus_recipe_vectors.json');
const fixture = JSON.parse(fs.readFileSync(VECTORS, 'utf8'));

const failures = [];
let checks = 0;
const expect = (name, what, got, want) => {
	checks++;
	if (got !== want) failures.push(`${name}: ${what}\n    got  ${JSON.stringify(got)}\n    want ${JSON.stringify(want)}`);
};
const expectError = (name, what, fn, wantPath) => {
	checks++;
	try {
		fn();
		failures.push(`${name}: ${what} was accepted; expected RecipeError at ${JSON.stringify(wantPath)}`);
	} catch (e) {
		if (!(e instanceof RecipeError)) failures.push(`${name}: ${what} threw ${e && e.name}: ${e && e.message}`);
		else if (e.path !== wantPath) failures.push(`${name}: ${what} rejected at ${JSON.stringify(e.path)}, want ${JSON.stringify(wantPath)} (${e.msg})`);
	}
};

if (fixture.recipe_version !== RECIPE_VERSION) failures.push(`fixture is for recipe version ${fixture.recipe_version}, module speaks ${RECIPE_VERSION}`);

for (const v of fixture.valid) {
	let canon;
	try {
		canon = canonicalJson(v.input);
	} catch (e) {
		failures.push(`${v.name}: rejected a valid recipe: ${e.message}`);
		continue;
	}
	expect(v.name, 'canonical JSON', canon, v.canonical);
	expect(v.name, 'idempotent re-parse', canonicalJson(JSON.parse(canon)), v.canonical);
	expect(v.name, 'token', encodeRecipeToken(v.input), v.token);
	expect(v.name, 'token round-trip', canonicalJson(decodeRecipeToken(v.token)), v.canonical);
	expect(v.name, 'pid', await recipePid(v.input), v.pid);
	expect(v.name, 'pid shape', PID_RE.test(v.pid), true);
	expect(v.name, 'pid is not a legacy id', isLegacyLocusId(v.pid), false);
}
// The two atlas_default vectors are the same recipe written two ways: they must agree with
// each other, and a genuinely different recipe must not (so this comparison can fail).
const byName = Object.fromEntries(fixture.valid.map((v) => [v.name, v]));
expect('equivalence', 'noisy == default (pid)', await recipePid(byName.atlas_default_reordered_noisy.input), await recipePid(byName.atlas_default.input));
expect('equivalence', 'sweep != default (pid)', (await recipePid(byName.spatial_sweep_no_query.input)) !== (await recipePid(byName.atlas_default.input)), true);

for (const v of fixture.invalid) expectError(v.name, 'invalid recipe', () => parseRecipe(v.input), v.error_path);

for (const a of fixture.adapter) {
	if (a.error_path !== undefined) {
		expectError(a.name, 'search body', () => retrievalFromSearchBody(a.body), a.error_path);
		continue;
	}
	const recipe = { v: RECIPE_VERSION, retrieval: retrievalFromSearchBody(a.body), clustering: a.clustering, members: a.members };
	expect(a.name, 'adapter canonical', canonicalJson(recipe), a.canonical);
}

for (const p of fixture.pids.valid) expect(`pid ${p.input}`, 'normalise', normalisePid(p.input), p.canonical);
for (const p of fixture.pids.invalid) {
	checks++;
	let accepted = null;
	try { accepted = normalisePid(p.input); } catch (e) { /* expected */ }
	if (accepted !== null) failures.push(`pid ${p.input} (${p.why}) was accepted as ${accepted}`);
}

if (failures.length) {
	console.error(`locus recipe: ${failures.length} of ${checks} checks FAILED\n\n` + failures.join('\n\n'));
	process.exit(1);
}
console.log(`locus recipe: ${checks} checks passed (${fixture.valid.length} valid, ${fixture.invalid.length} invalid, ${fixture.adapter.length} adapter, ${fixture.pids.valid.length + fixture.pids.invalid.length} pid vectors)`);
