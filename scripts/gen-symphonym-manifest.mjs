#!/usr/bin/env node
/**
 * Generate whg/webpack/js/symphonym-assets.js from the shipped Symphonym assets.
 *
 * WHY THIS EXISTS (place#283). The worker fetches its model and vocabularies by literal path
 * from /static/webpack/symphonym/. Webpack bundles carry a content hash and a ?v=<git-hash>;
 * these raw statics carry neither. So a deploy that changes them can serve a NEW symphonym.onnx
 * to a browser holding a CACHED char_vocab.json — and pairing a model with the wrong vocabulary
 * does not raise. It embeds plausible nonsense.
 *
 * And it does so NON-UNIFORMLY, which is what makes it dangerous rather than merely bad.
 * Measured across the v7 and v8 vocabularies: of 113,269 shared characters, 98 keep their id
 * (0.1%); by script, LATIN 52/1,128, CJK 0/93,316, CYRILLIC 0/375, ARABIC 0/1,102, GREEK 0/365.
 * The 52 stable characters are the frequent ASCII letters — enough for "London" and
 * "Bury St. Edmunds" to tokenise IDENTICALLY under a mispairing. The failure therefore PRESENTS
 * AS A WORKING DEPLOY and breaks exactly the non-Latin scripts a historical gazetteer exists for.
 *
 * Hence two mechanisms, and the second is the necessary one:
 *   - the sha256 goes in the fetch URL, so changed bytes are a changed URL (no stale cache);
 *   - the worker re-hashes what it received and refuses to run on a mismatch, which catches
 *     every other route in — wrong build, partial deploy, two of three files copied.
 *
 * Run after changing ANY file in static/webpack/symphonym/:
 *     node scripts/gen-symphonym-manifest.mjs
 * It is checked by `npm run test:symphonym`, so a forgotten run is a test failure, not a
 * production surprise.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'static', 'webpack', 'symphonym');
const OUT = path.join(ROOT, 'whg', 'webpack', 'js', 'symphonym-assets.js');

// The model generation these assets are. It is what the client DECLARES to the gateway as
// `query_vector_model`; the gateway honours a client vector only if this names the generation it
// has loaded, and otherwise discards it and embeds server-side (correct, just not offloaded).
// Change it in the same commit as the assets — never on its own, in either direction.
const GENERATION = process.env.SYMPHONYM_GENERATION || 'v7';

// Verified at fetch time. The wasm is excluded deliberately: onnxruntime-web fetches it itself
// through ort.env.wasm.wasmPaths, so its bytes never pass through our hands. It still gets a
// versioned URL below, but it cannot be integrity-checked here and is not part of the
// model/vocabulary pairing that this guard exists to protect.
const VERIFIED = ['symphonym.onnx', 'char_vocab.json', 'script_vocab.json', 'lang_vocab.json'];
const VERSIONED_ONLY = ['ort-wasm-simd-threaded.wasm', 'ort-wasm-simd-threaded.mjs.js'];

const entries = [];
for (const name of [...VERIFIED, ...VERSIONED_ONLY]) {
  const p = path.join(DIR, name);
  if (!fs.existsSync(p)) {
    console.error(`missing asset: ${p}`);
    process.exit(1);
  }
  const buf = fs.readFileSync(p);
  entries.push({
    name,
    sha256: crypto.createHash('sha256').update(buf).digest('hex'),
    bytes: buf.length,
    verify: VERIFIED.includes(name),
  });
}

const body = entries.map((e) =>
  `  ${JSON.stringify(e.name)}: { sha256: '${e.sha256}', bytes: ${e.bytes}, verify: ${e.verify} },`
).join('\n');

fs.writeFileSync(OUT, `// GENERATED by scripts/gen-symphonym-manifest.mjs — do not edit by hand.
// Regenerate after changing any file in static/webpack/symphonym/, in the SAME commit.
// See place#283 for why a model/vocabulary mispairing is silent and passes an English smoke test.

// The generation these assets are, declared to the gateway as \`query_vector_model\`. The gateway
// uses a client vector only if this names the generation it has loaded; otherwise it discards the
// vector and embeds server-side — correct results, no offload. Check it from outside at
// /api/health -> stores.symphonym.{version, client_vectors}.
export const SYMPHONYM_GENERATION = ${JSON.stringify(GENERATION)};

export const SYMPHONYM_ASSETS = {
${body}
};
`);

console.log(`wrote ${path.relative(ROOT, OUT)}  (generation ${GENERATION})`);
for (const e of entries) {
  console.log(`  ${e.verify ? 'verify ' : 'version'}  ${e.name.padEnd(30)} ${String(e.bytes).padStart(9)}  ${e.sha256.slice(0, 16)}…`);
}
