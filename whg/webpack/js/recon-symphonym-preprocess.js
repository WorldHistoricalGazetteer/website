// recon-symphonym-preprocess.js
// The Symphonym tokeniser, ported character-for-character from the CANONICAL implementation:
// `hf/inference.py` in the indexing repo, between its `--- BEGIN/END CANONICAL TOKENISER ---`
// markers (commit 97a8b31, 5 September 2026). Verified case-by-case against a golden fixture
// generated from that file — `npm run test:symphonym`.
//
// WHY THIS FILE IS A PORT AND NOT AN INTERPRETATION. Until 5 September 2026 there were four
// implementations of this tokeniser and they disagreed. The gateway tokenised a query differently
// from the way the 72.7M-document `toponyms` index had been embedded, so on 46,483,973 documents
// (63.9%) a query vector did not match that document's own stored vector; for CJK/Kana/Hangul the
// two were ANTI-correlated (cos -0.30) and those 3.9M documents were effectively unreachable —
// 0.3% rank-1 self-retrieval. That is fixed server-side. whg3 was the fourth implementation: it
// builds its own `query_vector` in the browser and posts it to /api/reconcile, so once the fixed
// gateway ships, a vector built the old way here would reintroduce the identical bug on the client
// side, where it would read as a server regression.
//
// The four things the old version of this file got wrong, each of which the fixture covers:
//
//   D1  Preprocess BY SCRIPT, before any character lookup. CJK/Hiragana/Katakana are romanised
//       through anyascii and lowercased; Hangul is decomposed to Jamo; everything else is
//       NFC-normalised. The old version looked up raw codepoints, so 北京 embedded as two CJK
//       characters where the index holds 'beijing'.
//   D2  U+0020 maps to <SPACE> (id 2), never to a dictionary lookup — the vocab file happens to
//       carry a literal space at id 12588, a row the training tokeniser can never emit. All OTHER
//       whitespace is dropped entirely.
//   D3  The language tag is lowercased AND stripped before lookup, so 'EN', ' en ' and 'en' agree.
//   D4  detect_script() SKIPS non-alphabetic characters. Counting every character sends
//       'Q85423919', 'GR-9408' and '2038年1月5日の日食' to OTHER because digits and hyphens
//       outnumber letters — it changes the script_id of plain Latin names too. This is the subtle
//       one; it affects 0.68% of live names and is invisible without a test that contains digits.
//
//   Plus the one DELIBERATE deviation from the training tokeniser, carried over from the canonical
//   Python: an empty id list becomes [<UNK>] rather than []. A zero-length sequence is fatal to the
//   encoder ("Cannot pack empty tensors"), and dropping non-space whitespace widens the class of
//   inputs that produce one from "" alone to any whitespace-only input.
//
// DO NOT edit this file to fix a mismatch. Change the canonical Python, regenerate the fixture,
// then re-port. One side alone is how the four implementations diverged in the first place.

import anyAscii from 'any-ascii';
import { isAlphaCodepoint, PY_WHITESPACE, pyStrip } from './symphonym-unicode.js';

export const PAD_ID = 0;
export const UNK_ID = 1;
export const SPACE_ID = 2;
export const LANG_UNK_ID = 0;
export const SCRIPT_OTHER = 'OTHER';

// Unicode blocks per script, in the SAME ORDER as the canonical `_SCRIPT_UNICODE_RANGES`. The order
// is load-bearing and the LATER entry wins: the Python builds a codepoint→script dict by iterating
// this list, so where ranges overlap the last write survives. `scriptOfCodepoint` therefore keeps
// scanning after a hit rather than breaking on the first one — the previous version of this file
// broke on first match, over a different and shorter table, which was a fifth divergence nobody
// had named until the differential corpus found it.
//
// THE PRECEDENCE RULE REPRODUCES A KNOWN DEFECT, DELIBERATELY. Exactly one block overlaps:
// U+FB00–FB17, Hebrew presentation forms shadowed by the Armenian ligatures, with the consequence
// that the Latin ligature 'ﬁ' (U+FB01) scores as ARMENIAN. That is wrong, and the indexing repo
// agrees it is wrong — but the 72.7M-document index was written with it, so here "correct" means
// "identical". Fixing it is a Symphonym v8 question with a full re-embed attached. Do not
// "improve" this scan.
const SCRIPT_UNICODE_RANGES = [
  ['LATIN', [[0x0000, 0x007F], [0x0080, 0x00FF], [0x0100, 0x017F],
             [0x0180, 0x024F], [0x0250, 0x02AF], [0x1D00, 0x1D7F],
             [0x1E00, 0x1EFF], [0x2C60, 0x2C7F], [0xA720, 0xA7FF],
             [0xAB30, 0xAB6F]]],
  ['CYRILLIC', [[0x0400, 0x04FF], [0x0500, 0x052F], [0x2DE0, 0x2DFF],
                [0xA640, 0xA69F]]],
  ['GREEK', [[0x0370, 0x03FF], [0x1F00, 0x1FFF]]],
  ['ARABIC', [[0x0600, 0x06FF], [0x0750, 0x077F], [0x08A0, 0x08FF],
              [0xFB50, 0xFDFF], [0xFE70, 0xFEFF]]],
  ['HEBREW', [[0x0590, 0x05FF], [0xFB00, 0xFB4F]]],
  ['DEVANAGARI', [[0x0900, 0x097F], [0xA8E0, 0xA8FF]]],
  ['BENGALI', [[0x0980, 0x09FF]]],
  ['TAMIL', [[0x0B80, 0x0BFF]]],
  ['TELUGU', [[0x0C00, 0x0C7F]]],
  ['MALAYALAM', [[0x0D00, 0x0D7F]]],
  ['KANNADA', [[0x0C80, 0x0CFF]]],
  ['GUJARATI', [[0x0A80, 0x0AFF]]],
  ['THAI', [[0x0E00, 0x0E7F]]],
  ['GEORGIAN', [[0x10A0, 0x10FF], [0x2D00, 0x2D2F]]],
  ['ARMENIAN', [[0x0530, 0x058F], [0xFB00, 0xFB17]]],
  ['HANGUL', [[0xAC00, 0xD7AF], [0x1100, 0x11FF], [0x3130, 0x318F],
              [0xA960, 0xA97F], [0xD7B0, 0xD7FF]]],
  ['CJK', [[0x4E00, 0x9FFF], [0x3400, 0x4DBF], [0x20000, 0x2A6DF],
           [0x2A700, 0x2B73F], [0x2B740, 0x2B81F], [0x2B820, 0x2CEAF],
           [0x2CEB0, 0x2EBEF], [0x30000, 0x3134F], [0x3000, 0x303F],
           [0xF900, 0xFAFF]]],
  ['HIRAGANA', [[0x3040, 0x309F], [0x1B000, 0x1B0FF]]],
  ['KATAKANA', [[0x30A0, 0x30FF], [0x31F0, 0x31FF], [0xFF65, 0xFF9F]]],
];

// Romanised via anyascii; decomposed to Jamo. Both sets are what the index was built with —
// changing either invalidates 72.7M stored vectors.
const ROMANISE_SCRIPTS = new Set(['CJK', 'HIRAGANA', 'KATAKANA']);
const DECOMPOSE_SCRIPTS = new Set(['HANGUL']);

// Later entry wins — see the note on SCRIPT_UNICODE_RANGES.
export function scriptOfCodepoint(cp) {
  let script = SCRIPT_OTHER;
  for (const [name, ranges] of SCRIPT_UNICODE_RANGES) {
    for (const [lo, hi] of ranges) {
      if (cp >= lo && cp <= hi) { script = name; break; }
    }
  }
  return script;
}

// --- Hangul → Jamo -------------------------------------------------------
const HANGUL_START = 0xAC00;
const HANGUL_END = 0xD7A3;
const N_VOWEL = 21;
const N_TAIL = 28;
const CHOSEONG = ['ㄱ', 'ㄲ', 'ㄴ', 'ㄷ', 'ㄸ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅃ', 'ㅅ',
                  'ㅆ', 'ㅇ', 'ㅈ', 'ㅉ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ'];
const JUNGSEONG = ['ㅏ', 'ㅐ', 'ㅑ', 'ㅒ', 'ㅓ', 'ㅔ', 'ㅕ', 'ㅖ', 'ㅗ', 'ㅘ',
                   'ㅙ', 'ㅚ', 'ㅛ', 'ㅜ', 'ㅝ', 'ㅞ', 'ㅟ', 'ㅠ', 'ㅡ', 'ㅢ', 'ㅣ'];
const JONGSEONG = ['', 'ㄱ', 'ㄲ', 'ㄳ', 'ㄴ', 'ㄵ', 'ㄶ', 'ㄷ', 'ㄹ', 'ㄺ',
                   'ㄻ', 'ㄼ', 'ㄽ', 'ㄾ', 'ㄿ', 'ㅀ', 'ㅁ', 'ㅂ', 'ㅄ', 'ㅅ',
                   'ㅆ', 'ㅇ', 'ㅈ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ'];

// Hangul syllables → Jamo; every other character passes through.
export function decomposeHangul(text) {
  let out = '';
  for (const char of text) {
    let code = char.codePointAt(0);
    if (code >= HANGUL_START && code <= HANGUL_END) {
      code -= HANGUL_START;
      out += CHOSEONG[Math.floor(code / (N_VOWEL * N_TAIL))];
      out += JUNGSEONG[Math.floor((code % (N_VOWEL * N_TAIL)) / N_TAIL)];
      const tail = code % N_TAIL;
      if (tail) out += JONGSEONG[tail];
    } else {
      out += char;
    }
  }
  return out;
}

// The dominant script name, COUNTING ONLY ALPHABETIC CHARACTERS (D4). Ties go to the script seen
// first, which is what Python's `max(counts.items(), key=…)` over an insertion-ordered dict does.
// A Map, not an object: object keys that look like integers would be reordered ahead of the rest.
export function detectScript(text) {
  const counts = new Map();
  for (const char of text) {
    const cp = char.codePointAt(0);
    if (!isAlphaCodepoint(cp)) continue;
    const script = scriptOfCodepoint(cp);
    counts.set(script, (counts.get(script) || 0) + 1);
  }
  if (counts.size === 0) return SCRIPT_OTHER;
  let best = null;
  let bestN = -1;
  for (const [script, n] of counts) if (n > bestN) { best = script; bestN = n; }
  return best;
}

// Romanise CJK/Kana, decompose Hangul, NFC-normalise everything else (D1).
export function preprocessText(text, script) {
  const s = script == null ? detectScript(text) : script;
  if (ROMANISE_SCRIPTS.has(s)) return anyAscii(text).toLowerCase();
  if (DECOMPOSE_SCRIPTS.has(s)) return decomposeHangul(text);
  return text.normalize('NFC');
}

// `Object.keys` on a 113,280-entry vocab is far too slow to repeat per name.
const vocabSizeCache = new WeakMap();
function vocabSize(charToId) {
  let n = vocabSizeCache.get(charToId);
  if (n === undefined) { n = Object.keys(charToId).length; vocabSizeCache.set(charToId, n); }
  return n;
}

// Preprocessed text → character ids, with vocabulary growth disabled.
export function encodeChars(text, charToId, script, maxLength) {
  const size = vocabSize(charToId);
  const ids = [];
  for (const char of preprocessText(text, script)) {
    if (char === ' ') {
      ids.push(SPACE_ID);                                   // D2 — never a dictionary lookup
    } else if (PY_WHITESPACE.has(char.codePointAt(0))) {
      continue;                                             // D2 — all other whitespace is dropped
    } else {
      const cid = charToId[char];
      // An id at or beyond the vocabulary's own size is vocabulary corruption; degrade to <UNK>
      // rather than indexing off the end of the embedding table.
      ids.push(cid == null || cid >= size ? UNK_ID : cid);
    }
  }
  const capped = maxLength != null && ids.length > maxLength ? ids.slice(0, maxLength) : ids;
  return capped.length ? capped : [UNK_ID];                 // the deliberate deviation; see header
}

// Language tag → id. Lowercased and stripped before lookup (D3).
export function encodeLang(lang, langToId) {
  if (lang == null || lang === '') return LANG_UNK_ID;
  const id = langToId[pyStrip(String(lang).toLowerCase())];
  return id == null ? LANG_UNK_ID : id;
}

// Script name → id, falling back to OTHER and then to 0.
export function encodeScript(script, scriptToId) {
  if (Object.prototype.hasOwnProperty.call(scriptToId, script)) return scriptToId[script];
  const other = scriptToId[SCRIPT_OTHER];
  return other == null ? 0 : other;
}

// (text, lang) → the four ONNX inputs. The single entry point every caller should use.
// vocabs: { charToId, scriptToId, langToId } — the *_to_id maps from the JSON vocab files.
// NOTE `length` is the number of IDS, not the number of characters in the input: romanisation,
// Jamo decomposition and dropped whitespace all change the count, and the encoder's mask is built
// from this. They coincided under the old raw-codepoint tokeniser, which is why nothing caught it.
export function tokenise(text, lang, vocabs, maxLength) {
  const script = detectScript(text);
  const charIds = encodeChars(text, vocabs.charToId, script, maxLength);
  return {
    charIds: Int32Array.from(charIds),
    scriptId: encodeScript(script, vocabs.scriptToId),
    langId: encodeLang(lang, vocabs.langToId),
    length: charIds.length,
  };
}
