"""Adapter: an EDOPS ``/api/signature`` result -> the PROVISIONAL ``whgmodal`` payload.

Prototype (beta only). Karl Grossner's ``/whgmodal`` endpoint does not exist yet and
its payload is not agreed, so this module defines the shape WHG proposes
(``developer/edops-whgmodal-payload-proposal.md``) and builds it from what the live
``/api/signature`` service returns today. THE SWAP POINT is ``fetch_whgmodal``: when
the real endpoint exists, that one function calls it (and ``from_signature_result`` can
be deleted); the view and the browser code only ever see this shape.

Rules this module keeps:

* No LLM and no invented science. The ``profile`` prose here is a small, rule-built
  PLACEHOLDER written from the same values the Signature tab shows, marked
  ``generated_by: "whg-adapter-placeholder"``; EDOPS's own rule-generated prose
  replaces it (only for Level 06 basins at first; at Level 08 ``profile`` is the
  placeholder, flagged so the page says so).
* Every passage carries the SCALE it describes (``place`` or ``basin`` or ``area``),
  so a reader cannot take a basin average for the place itself.
* Reconstructed values carry their hedging (EDOPS's own ``lmr_*_note`` strings are
  passed through verbatim, plus ``reconstructed: true``).
* Nothing WHG-side goes in: no names, ids, members, coordinates. Only EDOPS's values.
"""
from __future__ import annotations

from typing import Optional

from api import edop_client as edop

SCHEMA = "whgmodal/0-provisional"

PLACEHOLDER_PROSE_NOTE = (
    "Text generated by rules from the values in the Signature tab, standing in for EDOPS's own "
    "rule-generated profile, which is not yet available. No language model was used."
)

# Series EDOPS returns under Band T, with the key each point carries.
_LMR = (("pdsi", "pdsi_series", "pdsi"), ("air_anom_k", "air_series", "air_anom_k"),
        ("prate_anom_mm_day", "prate_series", "prate_anom_mm_day"))


def _series_block(t: dict) -> Optional[dict]:
    """Aligned per-year arrays from Band T's ``*_series`` lists, or None."""
    if not isinstance(t, dict) or t.get("_status") != "ok" or t.get("lmr_status") != "available":
        return None
    years = None
    out = {}
    for name, src, key in _LMR:
        pts = [p for p in (t.get(src) or []) if isinstance(p, dict) and p.get("year") is not None]
        if not pts:
            continue
        if years is None:
            years = [p["year"] for p in pts]
        by_year = {p["year"]: p.get(key) for p in pts}
        out[name] = [by_year.get(y) for y in years]
    if not years or not out:
        return None
    notes = [t[k] for k in ("lmr_out_of_range_note", "lmr_fidelity_note", "lmr_proxy_bias_note") if t.get(k)]
    return {"years": years, **out, "reconstructed": True, "scale": "grid_cell",
            "grid_cell": t.get("grid_cell"), "source": "LMR v2.1", "caveats": notes}


def _land_use_block(t: dict) -> Optional[dict]:
    hyde = (t or {}).get("hyde_land_use") if isinstance(t, dict) else None
    epochs = [e for e in ((hyde or {}).get("epochs") or []) if isinstance(e, dict) and e.get("year_ce") is not None]
    if not epochs:
        return None
    keep = ("cropland_km2", "grazing_km2", "pasture_km2", "rangeland_km2")
    return {"epochs": [{"year": e["year_ce"], **{k: e.get(k) for k in keep}} for e in epochs],
            "basin_area_km2": epochs[0].get("basin_area_km2"), "unit": "km2", "reconstructed": True,
            "scale": "basin", "source": "HYDE 3.4", "caveats": [hyde["_note"]] if hyde.get("_note") else []}


def _events_block(t: dict) -> Optional[dict]:
    evs = [e for e in ((t or {}).get("volcanic_events") or []) if isinstance(e, dict) and e.get("year_ad") is not None] \
        if isinstance(t, dict) else []
    if not evs:
        return None
    return {"events": [{"year": e["year_ad"], "month": e.get("month"), "vssi_tg": e.get("vssi_tg"),
                        "location": e.get("location")} for e in evs],
            "unit": "Tg sulphate", "reconstructed": True, "scale": "global", "source": "eVolv2k v4",
            "caveats": [t["volcanic_events_note"]] if t.get("volcanic_events_note") else []}


def _monthly_block(v: dict) -> Optional[dict]:
    temp, pre = v.get("tmp_dc_monthly"), v.get("pre_mm_monthly")
    ok = lambda a: isinstance(a, list) and len(a) == 12  # noqa: E731
    if not (ok(temp) or ok(pre)):
        return None
    out = {"months": list(range(1, 13)), "scale": "basin", "source": "WorldClim via BasinATLAS",
           "period": "about 1970-2000 CE (present-day long-run averages, not historical values)"}
    if ok(temp):
        out["temperature_c"] = temp
    if ok(pre):
        out["precipitation_mm"] = pre
    return out


def _fmt(v) -> str:
    return str(edop._num(v))


def _placeholder_sections(v: dict, summary: dict, scope_type: str) -> list:
    """Small rule-built passages, each saying its scale. Only values EDOPS returned."""
    secs = []
    if scope_type == "basin" and v.get("elev_point") is not None:
        secs.append({"id": "place_elevation", "title": "At this place", "scale": "place",
                     "text": f"The point's own elevation is about {_fmt(v['elev_point'])} m.", "caveats": []})
    clim = []
    if v.get("temp_yr") is not None:
        clim.append(f"mean annual temperature is {_fmt(v['temp_yr'])} °C")
    if v.get("precip_yr") is not None:
        clim.append(f"annual precipitation is {_fmt(v['precip_yr'])} mm")
    if clim:
        secs.append({"id": "basin_climate", "title": "Climate of the surrounding basin", "scale": "basin",
                     "text": "Across the whole drainage basin, " + " and ".join(clim)
                             + ". These are present-day long-run averages (about 1970-2000 CE), not values for the period "
                               "a record describes.",
                     "caveats": ["Present-day climate: not historical values."]})
    if v.get("runoff") is not None:
        secs.append({"id": "basin_water", "title": "Water in the surrounding basin", "scale": "basin",
                     "text": f"Annual runoff across the basin is about {_fmt(v['runoff'])} mm.", "caveats": []})
    t = summary.get("temporal") or {}
    if t.get("status") == "ok" and t.get("items"):
        yrs = t.get("years") or []
        span = f"{yrs[0]}-{yrs[1]} CE" if len(yrs) == 2 and None not in yrs else "the years asked"
        secs.append({"id": "basin_past", "title": f"Reconstructions for {span}", "scale": "basin",
                     "text": "Climate figures for these years are reconstructed, not observed, and come from a coarse "
                             "grid; the Charts tab draws them. They indicate tendencies, not weather at the place.",
                     "caveats": list(t.get("notes") or [])})
    return secs


def _sources_block(summary: dict, t: Optional[dict]) -> list:
    out = [{"id": k, "name": name, "status": "ok", "reason": None}
           for k, name in (summary.get("data_sources") or {}).items()
           if k not in ("temporal_climate", "volcanic", "land_use_temporal")]
    if t is not None:
        ok = t.get("_status") == "ok"
        lmr_ok = ok and t.get("lmr_status") == "available"
        ds = summary.get("data_sources") or {}
        out.append({"id": "temporal_climate", "name": ds.get("temporal_climate") or "LMR v2.1",
                    "status": "ok" if lmr_ok else "unavailable",
                    "reason": None if lmr_ok else (t.get("lmr_status") or t.get("_status") or "not returned")})
        out.append({"id": "volcanic", "name": ds.get("volcanic") or "eVolv2k v4",
                    "status": "ok" if ok and t.get("volcanic_event_count") is not None else "unavailable",
                    "reason": None if ok else (t.get("_status") or "not returned")})
        out.append({"id": "land_use_temporal", "name": ds.get("land_use_temporal") or "HYDE 3.4",
                    "status": "ok" if ok and (t.get("hyde_land_use") or {}).get("epochs") else "unavailable",
                    "reason": None if ok and (t.get("hyde_land_use") or {}).get("epochs") else "no epochs returned"})
    return out


def from_signature_result(result: dict) -> dict:
    """The whgmodal payload for one ``edop_client.fetch_signature`` result (any status)."""
    status = result.get("status")
    base = {"schema": SCHEMA, "status": status, "reason": result.get("reason"),
            "attribution": edop.ATTRIBUTION, "profile": None, "signature": None, "series": None,
            "sources": [], "version": None, "scope": None, "caveats": []}
    summary = edop.summarise(result)
    if summary is None:
        return base
    raw = result["raw"]
    scope_type = summary["scope"]
    unit = summary.get("unit") or {}
    base["scope"] = {"type": scope_type, "level": unit.get("level"), "basin_id": unit.get("basin_id"),
                     "n_basins": unit.get("n_basins"), "upstream_area_km2": unit.get("upstream_area_km2"),
                     "uncovered_pct": unit.get("uncovered_pct")}
    base["version"] = {"signature_version": summary.get("signature_version"), "generated": summary.get("generated"),
                       "profile_version": None}
    base["signature"] = {"headline": summary["headline"],
                         "bands": [{**b, "scale": "area" if scope_type == "area" else "basin"} for b in summary["bands"]],
                         "temporal": summary.get("temporal")}
    base["caveats"] = list(summary.get("caveats") or [])
    t_raw = (raw.get("signature_bands") or {}).get("T") if scope_type == "basin" else None
    if scope_type == "basin":
        v = edop._basin_values(raw)
        base["series"] = {"monthly": _monthly_block(v), "timeline": _series_block(t_raw),
                          "land_use": _land_use_block(t_raw), "volcanic": _events_block(t_raw)}
    else:
        v = {}
    base["sources"] = _sources_block(summary, t_raw if isinstance(t_raw, dict) else None)
    base["profile"] = {"generated_text": True, "generated_by": "whg-adapter-placeholder",
                       "level": unit.get("level"), "note": PLACEHOLDER_PROSE_NOTE,
                       "sections": _placeholder_sections(v, summary, scope_type)}
    return base


def fetch_whgmodal(result: dict) -> dict:
    """THE ONE-FUNCTION SWAP. Today: adapt the ``/api/signature`` result already fetched.
    Later: call EDOPS ``/whgmodal`` with the same request parameters (``result["request"]``),
    cache it like ``fetch_signature`` does, and return its JSON unchanged."""
    return from_signature_result(result)
